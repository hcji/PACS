def test_mock_analyst_emits_the_protocol_record_for_every_dimension():
    agent = VirtualAgent(MockProvider(), single("inhibition", 0.2), model_id="mock:m", seed=7)
    probes = EB.dialogue_probes(goals=ALL_DIMS, n=6, seed=42)
    result = measure_phenotype(
        agent, MockProvider(), MockProvider(),
        probes=probes, n_turns=6, goals=ALL_DIMS, seed=7,
    )
    details = result.feedback["dim_details"]
    assert set(details) == set(ALL_DIMS)
    for dim, record in details.items():
        assert 0 <= record["score"] <= 100, dim
        assert 0.0 <= record["confidence"] <= 1.0, dim
        assert isinstance(record["observations"], list) and record["observations"], dim
        assert isinstance(record["task_measurements"], list), dim
        assert isinstance(record["deviation"], (int, float)), dim
    # 剖面仍然是 0..1 的典型性（下游分析不必改）
    assert all(v is None or 0.0 <= v <= 1.0 for v in result.profile.dims.values())
