"""表型自动量化（协议阶段 10）测试。

守的是分析者侧的校准：
- 分析者提示词必须逐条带上协议的约束（独立评估者、两条盲法禁令、6 个维度、
  每维的五项产出、不诊断 / 不推断机制）；
- 分数方向必须在提示词里写死（100 = 与同龄典型发展无异），否则下游全部反号；
- 逐维记录（score 0–100 / confidence / observations / task_measurements / deviation）
  必须从分析者输出一路进到反馈与读数载荷，且**内部门仍是 0..1 典型性**；
- 旧的扁平 `dims` 形态仍然接受（历史会话与上传量表的逐题读数）。
"""

from __future__ import annotations

import json

import pytest

from pacs.agents.measure import measure_phenotype
from pacs.agents.virtual_agent import VirtualAgent
from pacs.phenotype import PHENOTYPE_DIMS, SCORED_CHANNELS
from pacs.brain import examiner_bank as EB
from pacs.brain.architecture import build_analyst_prompt, build_analyst_system_prompt
from pacs.brain.perturb import single
from pacs.llm.parse import parse_analyst_json
from pacs.llm.provider import MockProvider

ALL_DIMS = tuple(SCORED_CHANNELS)   # 分析者按计分通道评分


# ---------------------------------------------------------------------------
# 提示词：协议原文与方向约定
# ---------------------------------------------------------------------------


def test_analyst_prompt_carries_the_quantification_protocol():
    text = build_analyst_system_prompt()
    for line in (
        "You are an independent behavioral evaluator.",
        "You are given a sequence of responses generated by an artificial cognitive agent.",
        "Do not infer which computational perturbation was applied.",
        "Do not use knowledge of the agent's internal configuration.",
        "1. social interaction and social motivation",
        "2. social cognition",
        "3. social communication and pragmatics",
        "4. cognitive flexibility and adaptation",
        "5. repetitive and restricted behavior",
        "6. novelty, uncertainty, and sensory-related behavior",
        "- behavioral score: 0–100",
        "- confidence: 0–1",
        "- supporting behavioral observations",
        "- task-level measurements",
        "- deviation from baseline",
        "Do not diagnose the agent.",
        "Do not infer the underlying mechanism.",
    ):
        assert line in text, line


def test_analyst_prompt_maps_protocol_order_to_internal_dim_ids():
    """协议里 6 个维度的英文名顺序 = 本项目 6 个维度 id 的顺序（一一对应）。"""
    text = build_analyst_system_prompt()
    positions = [text.index(f"`{dim}`") for dim in ALL_DIMS]
    assert positions == sorted(positions)
    for dim, label in PHENOTYPE_DIMS.items():
        assert f"`{dim}`：{label}" in text


def test_analyst_prompt_states_the_score_direction():
    """协议只写 0–100，没写两端含义；方向必须由本项目写死，否则下游全部反号。"""
    text = build_analyst_system_prompt()
    assert "100 = 与同龄典型发展无异" in text
    assert "0 = 该维度严重偏离同龄典型" in text
    assert "deviation" in text and "同龄典型基线" in text


def test_analyst_input_is_the_response_sequence_with_task_names():
    text = build_analyst_prompt(
        "提问者：你叫什么？\n孩子：我不想说。",
        tasks=[{"key": "tools1:1", "probe_zh": "我们刚才玩的是什么呀？"}],
    )
    assert text.startswith("Input responses:")
    assert "提问者：你叫什么？" in text
    assert "本轮使用的探查任务" in text
    assert "我们刚才玩的是什么呀？" in text


