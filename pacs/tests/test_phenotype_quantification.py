def test_protocol_payload_becomes_dim_records_and_typicality():
    payload = json.dumps({
        "dimensions": {
            "social_cognition": {
                "score": 85, "confidence": 0.7,
                "observations": ["能推断他人持有不同信息"],
                "task_measurements": [{"task": "错误信念", "measurement": "答对"}],
                "deviation": -15,
            },
            "repetitive_restricted_behavior": {"score": 0.92},     # 分数写成比例也要认
        },
        "narrative": "总体表现接近同龄典型。",
        "notes": "",
    })
    parsed, error = parse_analyst_json(payload)
    assert error == ""
    # 内部门一律是 0..1 的典型性
    assert parsed["dims"]["social_cognition"] == pytest.approx(0.85)
    assert parsed["dims"]["repetitive_restricted_behavior"] == pytest.approx(0.92)
    detail = parsed["dim_details"]["social_cognition"]
    assert detail["score"] == 85.0
    assert detail["confidence"] == 0.7
    assert detail["deviation"] == -15.0
    assert detail["observations"] == ["能推断他人持有不同信息"]
    assert detail["task_measurements"] == [{"task": "错误信念", "measurement": "答对"}]
    # 置信度缺省时取逐维均值
    assert parsed["confidence"] == 0.7


def test_legacy_flat_dims_still_accepted():
    parsed, error = parse_analyst_json('{"dims": {"social_cognition": 0.5}}')
    assert error == ""
    assert parsed["dims"] == {"social_cognition": 0.5}
    assert parsed["dim_details"] == {}


